#!/usr/bin/env python3
"""
Haratna logical backup over the Supabase Management API (HTTPS only).

Used when pg_dump can't reach the database (no direct Postgres access). Every
production query runs with "read_only": true, which the API executes as
`supabase_read_only_user` inside a read-only transaction, so production can't
be modified.

  python3 -I scripts/backup/logical_backup.py export <out_dir>
  python3 -I scripts/backup/logical_backup.py verify <out_dir>   # restore into a local scratch DB and compare checksums

Output (never commit it - it contains personal data and password hashes):
  manifest.json     timestamp, Postgres version, latest migration, per-table counts + checksums
  schema.sql        DDL for public and private (tables, constraints, indexes, functions,
                    policies, triggers, grants) + storage policies + auth trigger
  platform.sql      column definitions of the Supabase-managed auth/storage tables (verification only)
  data.json         every row of public, auth, storage, supabase_migrations, plus sequence values,
                    taken in ONE snapshot (a single statement)
  restore.sql       loads data.json-equivalent rows back (generated by `verify`, embedded data)

Not included: realtime (transient), vault (secrets), extension-owned tables
(spatial_ref_sys), and storage file bytes (files live in object storage; only
their metadata rows are here).

The Management API token is never read by this script: the session proxy adds it.
"""
import datetime
import hashlib
import json
import os
import subprocess
import sys
import urllib.request

PROJECT = os.environ.get("SUPABASE_PROJECT_REF", "ckqwziutmqohihrenstz")
API = f"https://api.supabase.com/v1/projects/{PROJECT}/database/query"
DATA_SCHEMAS = ["public", "auth", "storage", "supabase_migrations"]
DDL_SCHEMAS = ["public", "private"]


def q(sql: str):
    req = urllib.request.Request(
        API,
        data=json.dumps({"query": sql, "read_only": True}).encode(),
        headers={"Content-Type": "application/json", "Authorization": "Bearer proxy-injected"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=300) as r:
        return json.loads(r.read())


def lit(values):
    return "array[" + ",".join("'" + v.replace("'", "''") + "'" for v in values) + "]::text[]"


def export(out: str):
    os.makedirs(out, exist_ok=True)
    os.chmod(out, 0o700)
    meta = q(
        "select now() as snapshot_at, current_setting('server_version') as server_version, "
        "(select max(version) from supabase_migrations.schema_migrations) as latest_migration, "
        "current_setting('transaction_read_only') as read_only, current_user as role"
    )[0]
    if meta["read_only"] != "on":
        sys.exit("refusing: the API did not run the query read-only")

    # ---- tables, columns (generated columns are left out of rows and checksums)
    cols = q(
        "select table_schema s, table_name t, column_name c, is_generated g, ordinal_position o "
        "from information_schema.columns where table_schema = any(" + lit(DATA_SCHEMAS) + ") "
        "and table_name in (select c.relname from pg_class c join pg_namespace n on n.oid=c.relnamespace "
        "  where c.relkind in ('r','p') and n.nspname = table_schema "
        "  and not exists (select 1 from pg_depend d where d.objid=c.oid and d.deptype='e')) "
        "order by 1,2,5"
    )
    tables = {}
    for r in cols:
        tables.setdefault(f'{r["s"]}.{r["t"]}', []).append((r["c"], r["g"] == "ALWAYS"))

    # ---- one statement = one consistent snapshot of every table, with server-side checksums
    parts = []
    for name, cs in sorted(tables.items()):
        gen = [c for c, g in cs if g]
        s, t = name.split(".")
        parts.append(
            f"'{name}', (select json_build_object('count', count(*), "
            f"'md5', md5(coalesce(string_agg(x.j::text, chr(10) order by md5(x.j::text), x.j::text), '')), "
            f"'rows', coalesce(jsonb_agg(x.j order by md5(x.j::text)), '[]'::jsonb)) "
            f"from (select to_jsonb(t) - {lit(gen)} as j from \"{s}\".\"{t}\" t) x)"
        )
    seqs = (
        "(select coalesce(json_object_agg(schemaname||'.'||sequencename, last_value), '{}') from pg_sequences "
        "where schemaname = any(" + lit(DATA_SCHEMAS) + "))"
    )
    # json_build_object takes at most 100 arguments: merge chunks of 40 tables (still one statement = one snapshot).
    tables_obj = "(" + " || ".join(
        "jsonb_build_object(" + ", ".join(parts[i:i + 40]) + ")" for i in range(0, len(parts), 40)
    ) + ")"
    snap_sql = (
        "select json_build_object('snapshot_at', now(), 'read_only', current_setting('transaction_read_only'), "
        "'sequences', " + seqs + ", 'tables', " + tables_obj + ") as snap"
    )
    snap = q(snap_sql)[0]["snap"]
    if snap["read_only"] != "on":
        sys.exit("refusing: snapshot not read-only")

    # ---- schema DDL for the app schemas (+ storage policies, auth trigger)
    ddl = []
    ddl.append(q(
        "select string_agg(format('create table if not exists %I.%I (%s);', n.nspname, c.relname, cols), E'\\n' order by n.nspname, c.relname) as s "
        "from pg_class c join pg_namespace n on n.oid=c.relnamespace "
        "cross join lateral (select string_agg(format('%I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod), "
        "  case when a.attgenerated='s' then ' generated always as ('||pg_get_expr(d.adbin,d.adrelid)||') stored' "
        "       when d.adbin is not null then ' default '||pg_get_expr(d.adbin,d.adrelid) else '' end, "
        "  case when a.attidentity in ('a','d') then ' generated '||case a.attidentity when 'a' then 'always' else 'by default' end||' as identity' else '' end, "
        "  case when a.attnotnull then ' not null' else '' end), ', ' order by a.attnum) as cols "
        "  from pg_attribute a left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum "
        "  where a.attrelid=c.oid and a.attnum>0 and not a.attisdropped) x "
        "where c.relkind in ('r','p') and n.nspname = any(" + lit(DDL_SCHEMAS) + ")"
    )[0]["s"] or "")
    ddl.append(q(
        "select string_agg(format('alter table %I.%I add constraint %I %s;', n.nspname, t.relname, c.conname, pg_get_constraintdef(c.oid)), E'\\n' "
        "order by case c.contype when 'p' then 1 when 'u' then 2 when 'c' then 3 else 4 end, n.nspname, t.relname, c.conname) as s "
        "from pg_constraint c join pg_class t on t.oid=c.conrelid join pg_namespace n on n.oid=t.relnamespace "
        "where n.nspname = any(" + lit(DDL_SCHEMAS) + ")"
    )[0]["s"] or "")
    ddl.append(q(
        "select string_agg(pg_get_indexdef(i.indexrelid)||';', E'\\n' order by 1) as s from pg_index i join pg_class t on t.oid=i.indrelid "
        "join pg_namespace n on n.oid=t.relnamespace where n.nspname = any(" + lit(DDL_SCHEMAS) + ") "
        "and not exists (select 1 from pg_constraint c where c.conindid=i.indexrelid)"
    )[0]["s"] or "")
    ddl.append("set check_function_bodies = off;\n" + (q(
        "select string_agg(pg_get_functiondef(p.oid)||';', E'\\n\\n' order by n.nspname, p.proname, p.oid) as s "
        "from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname = any(" + lit(DDL_SCHEMAS) + ") "
        "and p.prokind in ('f','p') and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e')"
    )[0]["s"] or ""))
    ddl.append(q(
        "select string_agg(format('alter table %I.%I enable row level security;', n.nspname, c.relname), E'\\n' order by 1) as s "
        "from pg_class c join pg_namespace n on n.oid=c.relnamespace where c.relrowsecurity and n.nspname = any(" + lit(DDL_SCHEMAS) + ")"
    )[0]["s"] or "")
    ddl.append(q(
        "select string_agg(format('create policy %I on %I.%I as %s for %s to %s%s%s;', policyname, schemaname, tablename, permissive, cmd, "
        "array_to_string(roles, ','), case when qual is not null then ' using ('||qual||')' else '' end, "
        "case when with_check is not null then ' with check ('||with_check||')' else '' end), E'\\n' order by schemaname, tablename, policyname) as s "
        "from pg_policies where schemaname = any(" + lit(DDL_SCHEMAS + ["storage"]) + ")"
    )[0]["s"] or "")
    ddl.append(q(
        "select string_agg(pg_get_triggerdef(t.oid)||';', E'\\n' order by 1) as s from pg_trigger t join pg_class c on c.oid=t.tgrelid "
        "join pg_namespace n on n.oid=c.relnamespace where not t.tgisinternal and (n.nspname = any(" + lit(DDL_SCHEMAS) + ") "
        "or (n.nspname='auth' and t.tgfoid in (select p.oid from pg_proc p join pg_namespace pn on pn.oid=p.pronamespace where pn.nspname = any(" + lit(DDL_SCHEMAS) + "))))"
    )[0]["s"] or "")
    # Grants come from the catalogs (information_schema only lists grants the
    # read-only role itself is party to).
    ddl.append(q(
        "select string_agg(format('grant usage on schema %I to %I;', n.nspname, r.rolname), E'\\n' order by 1) as s "
        "from pg_namespace n cross join lateral aclexplode(n.nspacl) a join pg_roles r on r.oid=a.grantee "
        "where n.nspname = any(" + lit(DDL_SCHEMAS) + ") and r.rolname in ('anon','authenticated','service_role') and a.privilege_type='USAGE'"
    )[0]["s"] or "")
    ddl.append(q(
        "select string_agg(format('grant %s on table %I.%I to %I;', a.privilege_type, n.nspname, c.relname, r.rolname), E'\\n' order by 1) as s "
        "from pg_class c join pg_namespace n on n.oid=c.relnamespace cross join lateral aclexplode(c.relacl) a join pg_roles r on r.oid=a.grantee "
        "where c.relkind in ('r','p','v','m') and n.nspname = any(" + lit(DDL_SCHEMAS) + ") and r.rolname in ('anon','authenticated','service_role') "
        "and a.privilege_type <> 'MAINTAIN'"
    )[0]["s"] or "")
    ddl.append(q(
        "select string_agg(format('grant %s on sequence %I.%I to %I;', a.privilege_type, n.nspname, c.relname, r.rolname), E'\\n' order by 1) as s "
        "from pg_class c join pg_namespace n on n.oid=c.relnamespace cross join lateral aclexplode(c.relacl) a join pg_roles r on r.oid=a.grantee "
        "where c.relkind = 'S' and n.nspname = any(" + lit(DDL_SCHEMAS) + ") and r.rolname in ('anon','authenticated','service_role')"
    )[0]["s"] or "")
    ddl.append(q(
        "select string_agg(format('revoke all on function %s from public; grant execute on function %s to %s;', p.oid::regprocedure, p.oid::regprocedure, r.roles), E'\\n' order by 1) as s "
        "from pg_proc p join pg_namespace n on n.oid=p.pronamespace cross join lateral (select string_agg(quote_ident(rr.rolname), ',') as roles "
        "  from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a join pg_roles rr on rr.oid=a.grantee "
        "  where rr.rolname in ('anon','authenticated','service_role') and a.privilege_type='EXECUTE') r "
        "where n.nspname = any(" + lit(DDL_SCHEMAS) + ") and r.roles is not null and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e')"
    )[0]["s"] or "")
    schema_sql = "-- Haratna schema backup (public, private + storage policies)\nset search_path = public, extensions;\n\n" + "\n\n".join(ddl) + "\n"

    # ---- platform tables (auth/storage/migrations) column definitions, for local verification only
    types = q(
        "select string_agg(format('do $e$ begin create type %I.%I as enum (%s); exception when duplicate_object then null; end $e$;', n.nspname, t.typname, "
        "(select string_agg(quote_literal(e.enumlabel), ',' order by e.enumsortorder) from pg_enum e where e.enumtypid=t.oid)), E'\\n') as s "
        "from pg_type t join pg_namespace n on n.oid=t.typnamespace where t.typtype='e' and n.nspname in ('auth','storage')"
    )[0]["s"] or ""
    plat = q(
        "select string_agg(format('create table if not exists %I.%I (%s);', n.nspname, c.relname, cols), E'\\n' order by n.nspname, c.relname) as s "
        "from pg_class c join pg_namespace n on n.oid=c.relnamespace "
        "cross join lateral (select string_agg(format('%I %s%s', a.attname, format_type(a.atttypid, a.atttypmod), "
        "  case when a.attgenerated='s' then ' generated always as ('||pg_get_expr(d.adbin,d.adrelid)||') stored' else '' end), ', ' order by a.attnum) as cols "
        "  from pg_attribute a left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum where a.attrelid=c.oid and a.attnum>0 and not a.attisdropped) x "
        "where c.relkind in ('r','p') and n.nspname in ('auth','storage','supabase_migrations')"
    )[0]["s"] or ""
    plat_keys = q(
        "select string_agg(format('alter table %I.%I add constraint %I %s;', n.nspname, t.relname, c.conname, pg_get_constraintdef(c.oid)), E'\\n' order by 1) as s "
        "from pg_constraint c join pg_class t on t.oid=c.conrelid join pg_namespace n on n.oid=t.relnamespace "
        "where c.contype in ('p','u') and n.nspname in ('auth','storage','supabase_migrations')"
    )[0]["s"] or ""
    plat_seqs = q(
        "select string_agg(format('create sequence if not exists %I.%I;', schemaname, sequencename), E'\\n') as s "
        "from pg_sequences where schemaname in ('auth','storage','supabase_migrations')"
    )[0]["s"] or ""
    platform_sql = ("-- Supabase-managed tables (column shapes, keys and sequences, for verification)\n"
                    + types + "\n" + plat_seqs + "\n" + plat + "\n" + plat_keys + "\n")

    with open(os.path.join(out, "schema.sql"), "w") as f:
        f.write(schema_sql)
    with open(os.path.join(out, "platform.sql"), "w") as f:
        f.write(platform_sql)
    with open(os.path.join(out, "data.json"), "w") as f:
        json.dump({"snapshot_at": snap["snapshot_at"], "sequences": snap["sequences"],
                   "generated": {k: [c for c, g in v if g] for k, v in tables.items()},
                   "tables": {k: v["rows"] for k, v in snap["tables"].items()}}, f)
    manifest = {
        "project": PROJECT,
        "snapshot_at": snap["snapshot_at"],
        "exported_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "server_version": meta["server_version"],
        "latest_migration": meta["latest_migration"],
        "role": meta["role"],
        "read_only": True,
        "tables": {k: {"count": v["count"], "md5": v["md5"]} for k, v in snap["tables"].items()},
        "files": {},
    }
    for fn in ("schema.sql", "platform.sql", "data.json"):
        with open(os.path.join(out, fn), "rb") as f:
            manifest["files"][fn] = hashlib.sha256(f.read()).hexdigest()
    with open(os.path.join(out, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=1)
    for fn in os.listdir(out):
        os.chmod(os.path.join(out, fn), 0o600)
    total = sum(v["count"] for v in manifest["tables"].values())
    print(f"snapshot {snap['snapshot_at']} | {len(tables)} tables | {total} rows | latest migration {meta['latest_migration']}")


def psql(db, sql=None, file=None, capture=False):
    cmd = ["su", "postgres", "-c", f"psql -q -X -v ON_ERROR_STOP=1 -At -d {db}"]
    data = sql if sql is not None else open(file).read()
    r = subprocess.run(cmd, input=data, text=True, capture_output=True)
    if r.returncode != 0:
        raise SystemExit(f"psql failed: {r.stderr[-2000:]}")
    return r.stdout


def write_restore(out, columns):
    """restore.sql: replaces table contents from the backup (one transaction, triggers off)."""
    data = json.load(open(os.path.join(out, "data.json")))
    lines = ["-- Haratna data restore from the logical backup. Run as postgres in ONE transaction:",
             "--   psql -1 -v ON_ERROR_STOP=1 -f restore.sql",
             "-- Triggers and FK checks are suspended for the load (session_replication_role = replica).",
             "set session_replication_role = replica;", "set timezone = 'UTC';"]
    for name, rows in sorted(data["tables"].items()):
        s, t = name.split(".")
        lines.append(f'delete from "{s}"."{t}";')
        if rows:
            cols = columns[name]
            payload = json.dumps(rows)
            if "$haratna$" in payload:
                raise SystemExit("payload contains the dollar-quote tag")
            lines.append(f'insert into "{s}"."{t}" ({cols}) select {cols} from jsonb_populate_recordset(null::"{s}"."{t}", $haratna${payload}$haratna$::jsonb);')
    for seq, val in sorted(data["sequences"].items()):
        if val is not None:
            sn, n = seq.split(".")
            lines.append(f"select setval('\"{sn}\".\"{n}\"', {int(val)}, true);")
    lines.append("set session_replication_role = origin;")
    with open(os.path.join(out, "restore.sql"), "w") as f:
        f.write("\n".join(lines) + "\n")
    os.chmod(os.path.join(out, "restore.sql"), 0o600)


def verify(out):
    """Restores schema + data into a fresh local database and compares every table checksum."""
    man = json.load(open(os.path.join(out, "manifest.json")))
    for fn, h in man["files"].items():
        with open(os.path.join(out, fn), "rb") as f:
            if hashlib.sha256(f.read()).hexdigest() != h:
                raise SystemExit(f"file checksum mismatch: {fn}")
    data = json.load(open(os.path.join(out, "data.json")))
    db = "haratna_backup_verify"
    subprocess.run(["su", "postgres", "-c", f"dropdb --if-exists {db}; createdb {db}"], check=True)
    boot = open(os.path.join(os.path.dirname(__file__), "verify_bootstrap.sql")).read()
    psql(db, boot)
    psql(db, open(os.path.join(out, "platform.sql")).read())
    psql(db, "set search_path = public, extensions;\n" + open(os.path.join(out, "schema.sql")).read())
    # Column lists (generated columns are recomputed, never inserted), then restore
    # through restore.sql itself so the documented procedure is what gets tested.
    columns = {}
    for name in sorted(data["tables"]):
        s_, t_ = name.split(".")
        columns[name] = psql(db, f"select string_agg(quote_ident(attname), ',' order by attnum) from pg_attribute "
                                 f"where attrelid='\"{s_}\".\"{t_}\"'::regclass and attnum>0 and not attisdropped and attgenerated='';").strip()
    write_restore(out, columns)
    subprocess.run(["su", "postgres", "-c", f"psql -q -X -1 -v ON_ERROR_STOP=1 -d {db}"],
                   stdin=open(os.path.join(out, "restore.sql")), check=True, capture_output=True)
    bad = []
    for name, info in sorted(man["tables"].items()):
        s, t = name.split(".")
        gen = data["generated"].get(name, [])
        got = psql(db, "set timezone='UTC';\n"
                       f"select count(*)||' '||md5(coalesce(string_agg(x.j::text, chr(10) order by md5(x.j::text), x.j::text), '')) "
                       f"from (select to_jsonb(t) - {lit(gen)} as j from \"{s}\".\"{t}\" t) x;").strip().splitlines()[-1]
        cnt, md5 = got.split(" ")
        if int(cnt) != info["count"] or md5 != info["md5"]:
            bad.append((name, info["count"], cnt))
    total = sum(v["count"] for v in man["tables"].values())
    if bad:
        print(f"VERIFY FAILED for {len(bad)} table(s):")
        for b in bad:
            print("  ", b)
        sys.exit(1)
    print(f"VERIFY OK: {len(man['tables'])} tables, {total} rows restored locally; every count and checksum matches production snapshot {man['snapshot_at']}")


if __name__ == "__main__":
    if len(sys.argv) != 3 or sys.argv[1] not in ("export", "verify"):
        sys.exit(__doc__)
    {"export": export, "verify": verify}[sys.argv[1]](sys.argv[2])
