/** "3h 12m" style, for response times. */
export function formatDuration(seconds: number | null, t: AdminDict): string | null {
  if (seconds == null || !Number.isFinite(seconds)) return null;
  const s = Math.max(0, Math.round(seconds));
  const d = Math.floor(s / 86400);
  const h = Math.floor((s % 86400) / 3600);
  const m = Math.floor((s % 3600) / 60);
  if (d) return `${d}${t.durations.d} ${h}${t.durations.h}`;
  if (h) return `${h}${t.durations.h} ${m}${t.durations.m}`;
  if (m) return `${m}${t.durations.m}`;
  return `${s}${t.durations.s}`;
}

export function formatDateTime(iso: string | null, locale: AdminLocale): string {
  if (!iso) return '—';
  return new Intl.DateTimeFormat(locale === 'ar' ? 'ar-SA-u-ca-gregory-nu-latn' : 'en-GB', {
    timeZone: 'Asia/Riyadh',
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(new Date(iso));
}
